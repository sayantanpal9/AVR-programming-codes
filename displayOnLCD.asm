.INCLUDE "M32DEF.INC"
.ORG 0X0000

MAIN:
	LDI R16, LOW(RAMEND)
	OUT SPL, R16
	LDI R16, HIGH(RAMEND)
	OUT SPH, R16

	LDI R30, 0X80
	LDI R31, 0X00
	LDI R16, 'H'
	ST Z+, R16
	LDI R16, 'E'
	ST Z+, R16
	LDI R16, 'Y'
	ST Z+, R16
	LDI R16, 0XFF
	OUT DDRA, R16
	OUT DDRB, R16
	CBI PORTB, PINB1
	LDI R16, 0X38
	RCALL CMD
	LDI R16, 0X0C
	RCALL CMD
	LDI R16, 0X01
	RCALL CMD
	LDI R16, 0X06
	RCALL CMD
	LDI R30, 0X80
	LDI R31, 0X00
	LD R16, Z+
	RCALL DIS
	LD R16, Z+
	RCALL DIS
	LD R16, Z+
	RCALL DIS
	RCALL INF

	RJMP MAIN

	DELAY:
		LDI R18, 0XFF
		DOTHIS:
			LDI R19, 0XFF
			DOTHAT:
				DEC R19
				BRNE DOTHAT
				DEC R18
				BRNE DOTHIS
		RET
	CMD:
		CBI PORTB, PINB0
		OUT PORTA, R16

		SBI PORTB, PINB1
		RCALL DELAY
		CBI PORTB, PINB1
		RET
	DIS:
		SBI PORTB, PINB0
		OUT PORTA, R16

		SBI PORTB, PINB1
		RCALL DELAY
		CBI PORTB, PINB1
		RET

	INF:
		RJMP INF
