.INCLUDE"M32DEF.INC"
.ORG 0X0000

MAIN:
	LDI R16, HIGH(RAMEND)
	OUT SPH, R16
	LDI R16, LOW(RAMEND)
	OUT SPL, R16
	LDI R30, 0X80
	LDI R31, 0X00
	LDI R16, 0B00111111
	ST Z+, R16
	LDI R16, 0B00000110
	ST Z+, R16
	LDI R16, 0B01011011
	ST Z+, R16
	LDI R16, 0B01001111
	ST Z+, R16
	LDI R16, 0B01100110
	ST Z+, R16
	LDI R16, 0B01101101
	ST Z+, R16
	LDI R16, 0B01111101
	ST Z+, R16
	LDI R16, 0B00000111
	ST Z+, R16
	LDI R16, 0B01111111
	ST Z+, R16
	LDI R16, 0B01101111
	ST Z+, R16
	LDI R16, 0XFF
	OUT DDRA, R16
	OUT DDRC, R16

	LDI R19, 0X00
	LDI R30, 0X80
	LDI R31, 0X00
	LDI R17, 0X00

	LOOP:
		RCALL GETDIG1
		OUT PORTA, R16
		RCALL GETDIG2
		OUT PORTC, R16
		RCALL DELAY
		INC R19
		CPI R19, 10
		IN R16, SREG
		SBRS R16, 0
		RCALL RESET
		CPI R17, 10
		IN R16, SREG
		SBRS R16, 0
		RCALL RESET2
		

		RJMP LOOP

	RET
	DELAY:
		LDI R18, 0X04
		DOTHIS:
			LDI R20, 0XFF
			DOTHAT:
				LDI R21, 0XFF
				AGAIN:
					DEC R21
					BRNE AGAIN
					DEC R20
					BRNE DOTHAT
					DEC R18
					BRNE DOTHIS
		RET

		RET
	RESET:
		LDI R19, 0X00
		INC R17
		RET
	RESET2:
		LDI R17, 0X00
		RET
	GETDIG1:
		LDI R30, 0x80   
		LDI R31, 0x00   
    
		ADD R30, R19     
		CLR R18          
		ADC R31, R18     
    
		LD R16, Z        
		RET
	GETDIG2:
		LDI R30, 0x80   
		LDI R31, 0x00   
    
		ADD R30, R17    
		CLR R18          
		ADC R31, R18     
    
		LD R16, Z        
		RET
