.INCLUDE"M32DEF.INC"
.ORG 0X0000

MAIN:
	LDI R16, HIGH(RAMEND)
	OUT SPH, R16
	LDI R16, LOW(RAMEND)
	OUT SPL, R16
	LDI R16, 0XFF
	OUT DDRC, R16
	LDI R16, 0X00
	OUT DDRA, R16
	LDI R19, 0X00
	LOOP:
		INC R19
		LDI R16, (1<<REFS0)|(1<<ADLAR)
		OUT ADMUX, R16
		LDI R16, (1<<ADEN)|(1<<ADSC)|(1<<ADPS1)
		OUT ADCSRA, R16
		RCALL ADC_READ
		IN R16, ADCH
		CP R16, R19
		IN R16, SREG
		SBRC R16, 0
		RCALL OUT_ONE
		SBRS R16, 0
		RCALL OUT_ZERO
		



	RJMP MAIN

	DELAY:
		LDI R17,  0XFF
		DOTHAT:
			LDI R18, 0XFF
			DOTHIS:
				DEC R18
				BRNE DOTHIS
				DEC R17
				BRNE DOTHAT
			

		RET
	ADC_READ:
		READING:
			SBIC ADCSRA, ADSC
			RJMP READING
		RET
	OUT_ZERO:
		LDI R20, 0X00
		OUT PORTC, R20
		RET
	OUT_ONE:
		LDI R20, 0XFF
		OUT PORTC, R20
		RET
