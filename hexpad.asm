.INCLUDE"M32DEF.INC"
.ORG 0X0000

MAIN:
	LDI R16, HIGH(RAMEND)
	OUT SPH, R16
	LDI R16, LOW(RAMEND)
	OUT SPL, R16
	LDI R16, 0XF0
	OUT DDRA, R16
	LDI R16, 0XFF
	OUT DDRC, R16
	LDI R16, 0X10
	LDI R17, 0X00
	LDI R18, 0X00

	LOOP:
		LDI R18, 0X00
		LDI R16, 0B11101111
		OUT PORTA, R16
		IN R17, PINA
		NOP
		ANDI R17,0X0F
		RCALL FUNC
		INC R18
		LDI R16, 0B11011111
		OUT PORTA, R16
		IN R17, PINA
		NOP
		ANDI R17,0X0F
		RCALL FUNC
		INC R18
		LDI R16, 0B10111111
		OUT PORTA, R16
		IN R17, PINA
		NOP
		ANDI R17,0X0F
		RCALL FUNC
		INC R18
		LDI R16, 0B01111111
		OUT PORTA, R16
		IN R17, PINA
		NOP
		ANDI R17,0X0F
		RCALL FUNC


		RJMP LOOP
		

	RJMP MAIN
	FUNC:
		LDI R20, 0X03
		CPI R17, 0B00000111
		
		IN R19, SREG
		NOP
		SBRC R19, 1
		RCALL DISP
		DEC R20
		CPI R17, 0B00001011
		
		IN R19, SREG
		NOP
		SBRC R19, 1
		RCALL DISP
		DEC R20
		CPI R17, 0B00001101
		
		IN R19, SREG
		NOP
		SBRC R19, 1
		RCALL DISP
		DEC R20
		CPI R17, 0B00001110
		
		IN R19, SREG
		NOP
		SBRC R19, 1
		RCALL DISP
		

		RET
	DISP:
		MOV R21, R18
		MOV R22, R20
		LSL R22
		LSL R22
		ADD R21, R22
		OUT PORTC, R21
		
		RET
